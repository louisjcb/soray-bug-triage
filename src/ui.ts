import { ActionRowBuilder, ButtonBuilder, ButtonStyle, EmbedBuilder } from "discord.js";
import type { Severity, TriageResult } from "./types.js";

const SEVERITY_COLORS: Record<Severity, number> = {
  low: 0x5b8cff,
  medium: 0xf2c94c,
  high: 0xf2994a,
  critical: 0xeb5757,
};

function truncate(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

export function buildProposalEmbed(triage: TriageResult): EmbedBuilder {
  const steps = triage.stepsToReproduce.length
    ? triage.stepsToReproduce.map((step, index) => `${index + 1}. ${step}`).join("\n")
    : "Not provided";

  return new EmbedBuilder()
    .setTitle(truncate(triage.title, 256))
    .setDescription(truncate(triage.summary || "No summary.", 4096))
    .setColor(SEVERITY_COLORS[triage.severity])
    .addFields(
      { name: "Severity", value: triage.severity, inline: true },
      { name: "Platform", value: truncate(triage.platform, 1024), inline: true },
      { name: "Steps to reproduce", value: truncate(steps, 1024) },
      { name: "Expected", value: truncate(triage.expectedBehavior, 1024) },
      { name: "Actual", value: truncate(triage.actualBehavior, 1024) },
    )
    .setFooter({
      text: `Confidence ${Math.round(triage.confidence * 100)}%. Generated by AI, please review.`,
    });
}

export function buildButtons(proposalId: string): ActionRowBuilder<ButtonBuilder> {
  return new ActionRowBuilder<ButtonBuilder>().addComponents(
    new ButtonBuilder()
      .setCustomId(`soray:create:${proposalId}`)
      .setLabel("Create GitHub issue")
      .setStyle(ButtonStyle.Success),
    new ButtonBuilder()
      .setCustomId(`soray:dismiss:${proposalId}`)
      .setLabel("Dismiss")
      .setStyle(ButtonStyle.Secondary),
  );
}
